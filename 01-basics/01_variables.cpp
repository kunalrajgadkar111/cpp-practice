// C++ Variables Practice
// This file contains basic examples of variables in C++.

#include <iostream>
using namespace std;

int main() {

    int age = 34;
    float height = 5.5;
    char grade = 'A';
    string name = "Kunal";
    bool isStudent = true;

    cout << "Name: " << name << endl;
    cout << "Age: " << age << endl;
    cout << "Height: " << height << endl;
    cout << "Grade: " << grade << endl;
    cout << "Student: " << isStudent << endl;

    return 0;
}
